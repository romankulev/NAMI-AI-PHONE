GREETING_PROMPT = (
    "Здравствуйте! Вы позвонили в NAMI BEAUTY. Подскажите, с какой услугой вам помочь?"
)


def main() -> None:
    replacements = {
        "ELEVENLABS_LLM_MODEL": "ELEVENLABS_LLM_MODEL=gpt-4.1-mini",
        "REALTIME_SYSTEM_PROMPT": f"REALTIME_SYSTEM_PROMPT={json.dumps(SYSTEM_PROMPT, ensure_ascii=False)}",
        "REALTIME_GREETING_PROMPT": f"REALTIME_GREETING_PROMPT={json.dumps(GREETING_PROMPT, ensure_ascii=False)}",
    }
    lines = ENV_PATH.read_text(encoding="utf-8").splitlines()
    output: list[str] = []
    replaced: set[str] = set()

    for line in lines:
        key = line.partition("=")[0]
        if key in replacements:
            if key not in replaced:
                output.append(replacements[key])
                replaced.add(key)
            continue
        output.append(line)

    for key, replacement in replacements.items():
        if key not in replaced:
            output.append(replacement)

    ENV_PATH.write_text("\n".join(output) + "\n", encoding="utf-8")
    ENV_PATH.chmod(0o600)
    print("NAMI prompt updated")


if __name__ == "__main__":
    main()
